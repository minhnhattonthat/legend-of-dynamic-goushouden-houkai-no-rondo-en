"""Write tools/debug/maps.tsv: every field-test map (id, Japanese name, discarded flag) from the original ROM.

    python -X utf8 tools/debug/mapnames.py

The field test (debug top menu 2 -> 0) lists 0x137 maps; its name table is 0x137 u32 SJIS pointers at ROM 0x0FA814
(literal at 0x08016946, count at 0x08016940). warp.lua reaches map N as scene map_NNN (steps 2,0,map=N).
Names containing （廃棄） ("discarded") are unused maps: listed, but warp_all.py skips them.
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE, COUNT = 0x0FA814, 0x137


def main():
    rom = next((ROOT / "rom").glob("*.gba")).read_bytes()
    lines = ["# id\tname\tdiscarded  (generated by tools/debug/mapnames.py from the original ROM)"]
    for i in range(COUNT):
        p = struct.unpack_from("<I", rom, TABLE + 4 * i)[0] - 0x08000000
        name = rom[p:rom.index(b"\0", p)].decode("cp932")
        lines.append(f"{i}\t{name}\t{int('廃棄' in name)}")
    (ROOT / "tools" / "debug" / "maps.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{COUNT} maps -> tools/debug/maps.tsv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
