def width(text, gap=1):
    return sum(len(G[c][0]) for c in text) + gap * (len(text) - 1)


def mask(text, gap=1):
    pts, x = set(), 0
    for c in text:
        g = G[c]
        for y, row in enumerate(g):
            for dx, ch in enumerate(row):
                if ch == "#":
                    pts.add((x + dx, y))
        x += len(g[0]) + gap
    return pts, x - gap, H
