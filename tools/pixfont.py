def width(text, gap=1):
    return sum(len(G[c][0]) for c in text) + gap * (len(text) - 1)


def mask(text, gap=1, font=None):
    font = font or G
    pts, x = set(), 0
    for c in text:
        g = font[c]
        for y, row in enumerate(g):
            for dx, ch in enumerate(row):
                if ch == "#":
                    pts.add((x + dx, y))
        x += len(g[0]) + gap
    return pts, x - gap, max(len(font[c]) for c in text)
